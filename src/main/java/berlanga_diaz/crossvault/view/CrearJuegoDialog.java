    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        String titulo = txtNombre.getText().trim();
        String genero = (String) cbGenero.getSelectedItem();

        if (!ValidationAPI.esCampoRequeridoValido(titulo)) {
            JOptionPane.showMessageDialog(this, I18n.get("error.campos_vacios"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        Juego nuevo = new Juego(titulo, genero);
        int stockTotal = 0;

        for (Plataforma p : Plataforma.values()) {
            if (checksPlataforma.get(p).isSelected()) {
                int cant = (int) spinnersStock.get(p).getValue();
                nuevo.setStock(p, cant);
                stockTotal += cant;
            }
        }

        if (stockTotal <= 0) {
            JOptionPane.showMessageDialog(this, I18n.get("error.juego_sin_stock"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        gestor.agregarJuego(nuevo);
        dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

