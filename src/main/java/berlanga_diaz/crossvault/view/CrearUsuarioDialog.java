    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText().trim();
        String ap1 = txtApellido1.getText().trim();
        String ap2 = txtApellido2.getText().trim();
        String dni = txtDni.getText().trim();
        String tel = txtTelefono.getText().trim();

        if (!ValidationAPI.esCampoRequeridoValido(nombre) ||
            !ValidationAPI.esCampoRequeridoValido(ap1) ||
            !ValidationAPI.esCampoRequeridoValido(ap2) ||
            !ValidationAPI.esCampoRequeridoValido(dni) ||
            !ValidationAPI.esCampoRequeridoValido(tel)) {
            JOptionPane.showMessageDialog(this, I18n.get("error.campos_vacios"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!ValidationAPI.empiezaPorMayuscula(nombre) ||
            !ValidationAPI.empiezaPorMayuscula(ap1) ||
            !ValidationAPI.empiezaPorMayuscula(ap2)) {
            JOptionPane.showMessageDialog(this, I18n.get("error.nombre_mayuscula"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!ValidationAPI.esDniValido(dni)) {
            JOptionPane.showMessageDialog(this, I18n.get("error.dni_invalido"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!ValidationAPI.esTelefonoValido(tel)) {
            JOptionPane.showMessageDialog(this, I18n.get("error.telefono_invalido"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        Usuario nuevo = new Usuario(nombre, ap1, ap2, dni.toUpperCase(), tel, LocalDate.now());
        gestor.agregarUsuario(nuevo);
        dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

