    private void cargarTablaActivos() {
        modelo = (DefaultTableModel) tablaActivos.getModel();
        modelo.setRowCount(0);
        activos = gestor.getAlquileresActivosOrdenadosDesc();

        for (Alquiler a : activos) {
            modelo.addRow(new Object[]{
                String.format("%02d", a.getNumeroRegistro()),
                a.getJuego().getTitulo(),
                a.getUsuario().getNombreCompleto(),
                a.getPlataforma().getNombreMostrar(),
                a.getFechaInicio().format(FORMATO)
            });
        }
        if (!activos.isEmpty()) {
            tablaActivos.setRowSelectionInterval(0, 0);
        }
        actualizarSeleccion();
    }

    private void actualizarSeleccion() {
        int fila = tablaActivos.getSelectedRow();
        if (fila >= 0 && fila < activos.size()) {
            Alquiler a = activos.get(fila);
            lblValJoc.setText(a.getJuego().getTitulo());
            lblValUsuari.setText(a.getUsuario().getNombreCompleto());
            lblValPlataforma.setText(a.getPlataforma().getNombreMostrar());
            lblValData.setText(a.getFechaInicio().format(FORMATO));
            btnMarcarDevuelto.setEnabled(true);
        } else {
            lblValJoc.setText("-");
            lblValUsuari.setText("-");
            lblValPlataforma.setText("-");
            lblValData.setText("-");
            btnMarcarDevuelto.setEnabled(false);
        }
    }

