    private void itemRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemRegistrarActionPerformed
        // TODO add your handling code here:
        Usuario preUser = null;
        Juego preGame = null;
        int fila = tablaAlquileres.getSelectedRow();
        if (fila >= 0 && fila < listaActual.size()) {
            preUser = listaActual.get(fila).getUsuario();
            preGame = listaActual.get(fila).getJuego();
        }
        RegistrarAlquilerDialog dialog = new RegistrarAlquilerDialog(this, gestor, preUser, preGame);
        dialog.setVisible(true);
        actualizarTabla();
    }//GEN-LAST:event_itemRegistrarActionPerformed

