    private void itemBorrarUsuarioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemBorrarUsuarioActionPerformed
        // TODO add your handling code here:
        List<Usuario> usuarios = gestor.getUsuarios();
        if (usuarios.isEmpty()) return;

        Usuario seleccionado = (Usuario) JOptionPane.showInputDialog(
                this,
                I18n.get("usuario.borrar.seleccion"),
                I18n.get("usuario.borrar.titulo"),
                JOptionPane.QUESTION_MESSAGE,
                null,
                usuarios.toArray(),
                usuarios.get(0));

        if (seleccionado != null) {
            if (!gestor.eliminarUsuario(seleccionado)) {
                JOptionPane.showMessageDialog(this, I18n.get("error.usuario_alquileres_activos"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, I18n.get("msg.exito"));
            }
        }
    }//GEN-LAST:event_itemBorrarUsuarioActionPerformed

