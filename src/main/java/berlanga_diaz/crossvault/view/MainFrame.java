    public final void actualizarTabla() {
        modeloTabla.setRowCount(0);
        listaActual = gestor.getAlquileresOrdenadosDesc();

        for (Alquiler a : listaActual) {
            modeloTabla.addRow(new Object[]{
                String.format("%02d", a.getNumeroRegistro()),
                a.getJuego().getTitulo(),
                a.getUsuario().getNombreCompleto(),
                a.getPlataforma().getNombreMostrar(),
                a.getFechaInicio().format(FORMATO_FECHA),
                a.getFechaDevolucionPrevista().format(FORMATO_FECHA),
                a.getJuego().getGenero()
            });
        }

        AlquilerTableRenderer renderer = new AlquilerTableRenderer(listaActual);
        for (int i = 0; i < tablaAlquileres.getColumnCount(); i++) {
            tablaAlquileres.getColumnModel().getColumn(i).setCellRenderer(renderer);
        }

        lblTotalAlquileres.setText(I18n.get("lbl.total_alquileres") + listaActual.size());
    }

