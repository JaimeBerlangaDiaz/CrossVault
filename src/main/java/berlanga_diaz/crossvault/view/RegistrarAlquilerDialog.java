    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        Usuario usuario = (Usuario) cbUsuarios.getSelectedItem();
        Juego juego = (Juego) cbJuegos.getSelectedItem();
        Plataforma plataformaElegida = null;

        for (Map.Entry<Plataforma, JRadioButton> entry : radiosPlataforma.entrySet()) {
            if (entry.getValue().isSelected() && entry.getValue().isEnabled()) {
                plataformaElegida = entry.getKey();
                break;
            }
        }

        if (usuario == null || juego == null || plataformaElegida == null) {
            JOptionPane.showMessageDialog(this, I18n.get("error.sin_plataforma"), I18n.get("error.titulo"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        gestor.registrarAlquiler(usuario, juego, plataformaElegida);
        dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

