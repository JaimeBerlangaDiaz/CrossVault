    private void inicializarDatos(Usuario preUser, Juego preGame) {
        int sigNum = gestor.getAlquileresOrdenadosDesc().stream()
                .mapToInt(Alquiler::getNumeroRegistro)
                .max().orElse(0) + 1;
        txtNumRegistro.setText(String.format("%02d", sigNum));

        cbUsuarios.removeAllItems();
        for (Usuario u : gestor.getUsuarios()) {
            cbUsuarios.addItem(u);
        }
        if (preUser != null) cbUsuarios.setSelectedItem(preUser);

        cbJuegos.removeAllItems();
        for (Juego j : gestor.getJuegos()) {
            cbJuegos.addItem(j);
        }
        if (preGame != null) cbJuegos.setSelectedItem(preGame);

        cbJuegos.addActionListener(e -> actualizarDisponibilidadPlataformas());

        LocalDate hoy = LocalDate.now();
        txtFechaInicio.setText(hoy.format(FORMATO));
        txtFechaDevolucion.setText(hoy.plusDays(3).format(FORMATO));

        actualizarDisponibilidadPlataformas();
    }

    private void actualizarDisponibilidadPlataformas() {
        Juego juego = (Juego) cbJuegos.getSelectedItem();
        buttonGroup2.clearSelection();
        if (juego == null) return;

        lblGeneroValor.setText(I18n.get("alquiler.genero_lbl") + "  " + juego.getGenero());
        StringBuilder sb = new StringBuilder(I18n.get("alquiler.unidades_disponibles") + "\n");

        Plataforma[] ordenVisual = {Plataforma.PC, Plataforma.PS5, Plataforma.XBOX, Plataforma.SWITCH_2};
        boolean primeroSeleccionado = false;
        for (Plataforma p : ordenVisual) {
            int stock = juego.getStock(p);
            JRadioButton rb = radiosPlataforma.get(p);
            String sufijo = stock == 1 ? I18n.get("alquiler.unidad_disp") : I18n.get("alquiler.unidades_disp");
            rb.setText(p.getNombreMostrar() + "   (" + stock + " " + sufijo + ")");
            rb.setEnabled(stock > 0);

            if (stock > 0 && !primeroSeleccionado) {
                rb.setSelected(true);
                primeroSeleccionado = true;
            }
        }

        Plataforma[] ordenTexto = {Plataforma.PS5, Plataforma.XBOX, Plataforma.PC, Plataforma.SWITCH_2};
        for (Plataforma p : ordenTexto) {
            sb.append("   ").append(p.getNombreMostrar()).append(":    ").append(juego.getStock(p)).append("\n");
        }
        txtResumenStock.setText(sb.toString());
    }
